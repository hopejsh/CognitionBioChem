def scan(want: dict[str, int]) -> tuple[list[tuple], int]:
    r"""Match over the whole file, not line by line.

    These are hard-wrapped markdown files, and the count and its label land on either side of
    a newline often enough that a line-based scan reads "5 hypotheses" as the slate total when
    the sentence continues "decided by a test statistic". Every pattern here uses `\s+`, which
    spans the wrap; the line number is recovered from the match offset.
    """
    hits: list[tuple] = []
    checked = 0
    for path in surfaces():
        rel = str(path.relative_to(REPO))
        text = path.read_text(errors="replace")

        def line_of(pos: int) -> int:
            return text.count("\n", 0, pos) + 1

        def exempt(m: re.Match[str]) -> bool:
            a = text.rfind("\n", 0, m.start()) + 1
            b = text.find("\n", m.end())
            return EXEMPT_TOKEN in text[a: b if b != -1 else len(text)]

        def record(m: re.Match[str], key: str, got: int, claim: str) -> None:
            nonlocal checked
            checked += 1
            if got != want[key]:
                src = " ".join(m.group(0).split())
                hits.append((rel, line_of(m.start()), claim, got, want[key], src))

        allowed = restricted_for(rel)
        for key, pat, claim in RULES:
            if allowed is not None and key not in allowed:
                continue
            for m in pat.finditer(text):
                if not exempt(m):
                    record(m, key, _n(m.group(1)), claim)
        for key, implied, pat, claim in WORDED:
            if allowed is not None and key not in allowed:
                continue
            for m in pat.finditer(text):
                if not exempt(m):
                    record(m, key, implied, claim)
    return hits, checked


