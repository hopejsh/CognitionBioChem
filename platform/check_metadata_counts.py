#: ============================================================================================
#: DERIVED OR DECLARED -- the question this list keeps losing, and what was measured
#: ============================================================================================
#:
#: Three times now a count has gone stale on a surface this guard did not enumerate.
#: `app.js` and `index.html` (the workbench contradicted itself in three lines), and
#: `verify_all.py` ("the five suites whose success is exit 0", while SUITES held twelve).
#: Each was fixed by appending a line to SURFACES. That is a repair with a known half-life:
#: an enumerated list is a snapshot of who was paying attention on the day it was written.
#:
#: So the honest question is whether the list can be DERIVED -- every tracked text file,
#: minus a stated exemption list -- rather than declared. It was tried before it was
#: answered. Three measurements, all reproducible from this tree:
#:
#: (1) "Every TRACKED text file" is the wrong basis, and not marginally. `.gitignore` ends
#:     with `paper/`, and `docs/*.html`, `docs/*.docx`, `docs/*.pptx` are ignored above it.
#:     The whole manuscript tree is untracked: `paper/PROJECT_FACTS.md`,
#:     `paper/sec_*.md`, `paper/deck_copy*.json` -- 35 files this guard watches TODAY through
#:     SURFACE_GLOBS. Deriving from the index would UNWATCH the surface that carried
#:     "no ledger of such departures is compiled here", which is the worst single sentence
#:     the WORDED table has ever caught. A derivation is only as good as its universe, and
#:     this repository's universe is not the git index.
#:
#: (2) Deriving from the FILESYSTEM instead is strictly wider, and the width is the problem.
#:     Pointing `scan()` at every non-binary file outside `.git/` and the virtualenvs:
#:     2,369 files, 514 count claims bound, 299 reported stale. Restricting to the tree
#:     minus the directories this project already treats as records (`runs/`, `prespec/`,
#:     `data/superseded/`, `reviews/`, `research/`, `memory/`, `mas/`): 428 files, 348
#:     claims, 133 reported stale. Of those 133, the ones that were real defects were the
#:     two sentences in `verify_all.py`. Roughly one true positive for every forty-four false
#:     ones -- and the false ones are not noise to be tuned away, they are correct prose:
#:     `reviews/audit_r1.json` quoting the stale sentence it is reporting, `retractions.jsonl`
#:     holding the withdrawn wording by construction, `research/np_scaleout.json` saying
#:     "989 confirmed" about something else entirely, and this file's own rule table.
#:     A content guard at that ratio is a guard nobody believes, and a guard nobody believes
#:     is worse than no guard: it trains its readers to skip the output.
#:
#: (3) But the derivation DID find something. `verify_all.py` -- the file the README tells a
#:     reader to run, watched by `check_retractions.py` since the day it was written and by
#:     this guard never -- carried a live stale count that three rounds of enumeration and
#:     two independent readers had walked past. Enumeration is not merely imperfect here; it
#:     failed on the entry point.
#:
#: THE ANSWER, then, is that the question conflates two things a derived list is good for,
#: and they have opposite economics:
#:
#:     CONTENT   which files' counts get bound. Derivation is useless: 44:1 false positives,
#:               because most files that state a number are records, quotations or code.
#:               Stays declared, and stays narrow, and each narrowing carries its reason.
#:
#:     COVERAGE  which files exist at all, and whether anyone has DECIDED about each one.
#:               Derivation is exact: a file is either on a surface list or matched by a
#:               stated exemption, and that question has no false positives because it is not
#:               about what the file says. This is the question enumeration answers "no" to
#:               silently, and it is the question that would have caught `app.js`,
#:               `index.html` and `verify_all.py` on the day each was created.
#:
#: `coverage()` below implements the second. It walks the tree, and every text file must be
#: either a surface of this guard or matched by an entry in `UNWATCHED` carrying a reason. A
#: new file is neither, so it fails the guard with "neither watched nor exempted" and the
#: person adding it makes the call. That is the whole cost: one triage decision per new text
#: file, paid by the person who is looking at the file, instead of a stale-count round paid
#: by whoever finds it eighteen months later.
#:
#: WHAT MAKES THE DECLARED LIST TRUSTWORTHY, given that it stays declared:
#:   * it cannot silently omit a file -- `coverage()` fails on anything unclassified;
#:   * it cannot silently omit a RULE -- `platform/tools/mutation_suite.py` enumerates
#:     `RULES`, `WORDED`, `SURFACES` and `SURFACE_GLOBS` from this module's own code and
#:     reports UNCOVERED for any entry no mutation targets;
#:   * every exemption states a reason next to itself, and `--coverage` prints how many
#:     count claims the exempt set would have raised, so an exemption that is quietly hiding
#:     a stale count is visible as a number rather than as nothing.
#: An enumerated list with those three properties is a list whose gaps are loud. That is a
#: different object from the list this guard started with, which had none of them.

#: (glob, why this file is not a count surface). Matched with `fnmatch` against the
