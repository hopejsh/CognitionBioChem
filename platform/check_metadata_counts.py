EXEMPT_TOKEN = "SLATE-COUNT-HISTORICAL"

WORD_TO_INT = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7,
    "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13,
    "fourteen": 14, "fifteen": 15, "sixteen": 16, "seventeen": 17, "eighteen": 18,
    "nineteen": 19, "twenty": 20, "thirty": 30, "forty": 40,
}
#: Compounds matter more than they look: without "twenty-five" in the table the alternation
#: matches the "five" inside it and reports the manuscript's hypothesis count as 5.
for _tens, _base in (("twenty", 20), ("thirty", 30)):
    for _unit, _n in (("one", 1), ("two", 2), ("three", 3), ("four", 4), ("five", 5),
                      ("six", 6), ("seven", 7), ("eight", 8), ("nine", 9)):
        WORD_TO_INT[f"{_tens}-{_unit}"] = _base + _n

#: A numeral or a number-word, tolerating the markdown emphasis that wraps half of them.
#: Longest alternative first, so "twenty-five" wins over "five". The boundaries are the other
#: half of that lesson: without them, `\d{1,3}` matches the "1" of "H1 falsified" and the
#: "002" of a citation key, and every literature year in the manuscript becomes a slate count.
_WORDS = "|".join(sorted(WORD_TO_INT, key=len, reverse=True))
_NUMBODY = _WORDS + r"|\d{1,3}"
NUM = r"(?<![\w\-.])\*{0,2}(" + _NUMBODY + r")\*{0,2}(?![\w\-])"
#: The same thing without the capture. `record()` reads `m.group(1)`, so a pattern that names
#: two numbers must anonymise the one it is not binding -- otherwise "9 studies, 28
#: hypotheses" reports the hypothesis count as 9. Python's `re` has no variable-width
#: lookbehind, so this is the only way to require a neighbouring number without capturing it.
NUM_ANON = r"(?<![\w\-.])\*{0,2}(?:" + _NUMBODY + r")\*{0,2}(?![\w\-])"


def _n(raw: str) -> int:
    raw = raw.strip("*")
    return int(raw) if raw.isdigit() else WORD_TO_INT[raw.lower()]


#: (key into the expected table, compiled pattern, what the sentence is claiming).
#:
#: Each pattern binds a number to the label immediately beside it. The filler between the two
#: is spelled out rather than left as a wildcard: a loose `(NUM).{0,30}studies` matches "the
