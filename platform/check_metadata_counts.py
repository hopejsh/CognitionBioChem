def deviations_recorded() -> int:
    """Recount the deviation ledger from the study artefacts, not from a summary of them.

    `analysis.prespec_audit.deviations` is machine-generated per study. Counting it here
    rather than reading a total out of `slate.json` means the WORDED denial below is refuted
    by the same records a reader would open to check it.
    """
    total, seen = 0, set()
    for f in sorted((REPO / "data").glob("study_*.json")):
        body = json.loads(f.read_text())
        a = body.get("analysis") or body
        if not a.get("verdicts"):
            continue      # an input artefact with no decisions is not a study of the slate
        sid = a.get("study_id")
        if sid in seen:
            raise SystemExit(f"two artefacts claim study_id {sid}; refusing to guess")
        seen.add(sid)
        total += len((a.get("prespec_audit") or {}).get("deviations") or [])
    return total


def screen_population() -> tuple[int, int]:
    """Constructs and distinct peptides, from the two screens, which must agree.

    Both studies fold the same candidate set, so a disagreement means one was re-analysed and
    the other was not -- the stale-base failure this guard exists for, one level down.
    Refusing is better than picking a side.
    """
    seen = set()
    for name in ("study_candidate_screen.json", "study_msa_specificity.json"):
        a = json.loads((REPO / "data" / name).read_text())["analysis"]
        mult = a.get("peptide_multiplicity")
        if not mult:
            raise SystemExit(
                f"data/{name} carries no analysis.peptide_multiplicity: re-run that study "
                "with --analyse. Without it there is nothing to bind a candidate count to.")
        seen.add((mult["n_constructs"], mult["n_distinct_peptides"]))
    if len(seen) != 1:
        raise SystemExit(f"the two screens disagree about the population: {sorted(seen)}")
    return seen.pop()


