#!/usr/bin/env python3
"""Guard: every hand-typed slate count must equal the artefacts it summarises.

The defect this exists for
--------------------------
`CITATION.cff`, `codemeta.json`, `biotools.json`, `.zenodo.json` and `docs/REGISTRATION.md`
all said, verbatim, "Eight studies were pre-registered under content hashes before any data
was seen." That was true when it was written. Study #12, `interface-null-positive-control-v1`,
was registered on 2026-08-22, and none of the five sentences moved -- so the citable record,
the DOI description, the bio.tools entry and the RRID submission block all described a slate
with the retraction study removed from it. `docs/RELEASE_NOTES_v1.0.0.md` and `paper/` carry
the same count with the verdict totals attached to it.

Why the guards already in the repository could not see it
---------------------------------------------------------
The prose guard that used to run beside this one bound every numeral in the manuscript to an
artefact, and it reported 10 passed / 0 failed on a document that says "8 pre-registered
studies and 25 hypotheses". Two reasons, both deliberate: `8` and `25` were members of the
22,054-string set it collected from `data/`, and it exempted small counts as the ordinary
vocabulary of prose. Neither was a bug. No
membership test can distinguish a number with no basis from a number whose basis has MOVED --
`8` still sources correctly, to last month's slate.

That is the gap here: this guard does not ask whether a number appears somewhere in `data/`.
It asks whether the number standing next to the word `studies` is *the current* study count.

What it binds to
----------------
Nothing in this file is a constant. Every expected value is read at run time from
`data/slate.json` (itself generated by `platform/build_slate.py` from the artefacts),
`len(glob('prespec/*.json'))` and `len(verify_all.SUITES)`.

The number-word half is load-bearing
------------------------------------
Three of the four metadata files spelled it "Eight". A numeral-only scan finds nothing, which
is exactly why this went unnoticed while a repository full of numeric guards passed. Both
forms are scanned.

Scope, and what is deliberately NOT bound
-----------------------------------------
* The bare phrase "N study artefacts" is not bound either, and the reason is instructive:
  `docs/REGISTRATION.md` uses it to count the three artefacts that carry ChEMBL's share-alike
  licence, which is a different quantity wearing the same words. `.zenodo.json` now says
  "the artefacts of 9 studies", which this guard does bind. A pattern that cannot tell two
  meanings apart should be narrowed until it can, not left to cry wolf.
* Candidate counts ARE bound now, and why they were not is worth keeping. "13 candidates" was
  a live scientific question -- thirteen candidate-receptor constructs cover twelve distinct
  peptides, because de-duplication was applied on (peptide, target), which does not collapse
  one peptide declared against two receptors -- and a guard must not settle a scientific
  question by picking a side. The screens settle it themselves now:
  `analysis.peptide_multiplicity` in `data/study_candidate_screen.json` and
  `data/study_msa_specificity.json` records both counts, derived from the stored rows, and the
  two must agree or this guard refuses to run. So both numbers are read from those blocks like
  every other expected value. What is bound is the two unambiguous phrasings, "N
  candidate-receptor constructs" and "N distinct peptides", plus the one that was wrong on five
  surfaces: "N distinct candidates/designs" is bound to the PEPTIDE count, because the word
  "distinct" makes that sentence a claim about molecules rather than about rows.
* `prespec/**` and `data/superseded/**` are not scanned at all. A registered plan and a
  superseded artefact are records of what was true then; rewriting one to match today would
  destroy the property they exist for.
* Korean editions are scanned with the same English triggers, which will not fire on Korean
  labels. This gap is now OPEN, and is recorded rather than papered over. It used to be
  covered from the other side by a parity guard that required every number stated in English
  to appear in the Korean, so a corrected English count forced the Korean to follow. That
  guard watched report editions this repository no longer publishes and is no longer part of
  it. Nothing in a clone carries a Korean count today; if one ever returns, the parity check
  has to return with it.

Escape hatch
------------
Exactly one, and it must be visible: a line containing the token `SLATE-COUNT-HISTORICAL` is
skipped, for prose that deliberately quotes a superseded count (a release note frozen to what
that release said, a paragraph describing what a published DOI record still reads). Use it
rarely; a count with no such marker is a claim about the repository as it stands now.
"""

