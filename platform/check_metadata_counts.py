def _matches(rel: str, pattern: str) -> bool:
    """`fnmatch`, plus `dir/*` meaning the whole subtree rather than one level.

    `fnmatch`'s `*` crosses `/`, which is usually wrong and is exactly right here: an
    exemption for `runs/*` must cover `runs/2026-08-19T.../fold/log.txt` without anyone
    counting the levels.

    The consequence, stated because it is easy to misread the table above: these patterns are
    WIDER than they look. `data/*.json` covers `data/pae/x.json` too, and the `data/*/*`
    entries beside it are therefore redundant rather than load-bearing -- they are kept only
    because they name what lives there. Nothing here narrows; an exemption entry can only
    ever exempt more than its shape suggests, so a pattern must be written to be as specific
    as the reason it carries. That is why `paper/` is enumerated file by file.
    """
    return fnmatch.fnmatch(rel, pattern)


def coverage(watched: set[str]) -> tuple[list[str], list[tuple[str, str]]]:
    """Every text file in the tree, classified. Returns (unclassified, [(rel, reason)]).

    This is the derived half. It does not read a single count -- it asks only whether
    somebody has decided about each file, which is the question that has no false positives.
    """
    unclassified: list[str] = []
    exempt: list[tuple[str, str]] = []
    for path in sorted(REPO.rglob("*")):
        # Symlinks are followed, not skipped. `platform/tools/mutation_suite.py` builds its
        # scratch trees as real directories full of symlinks back to the repository, and
        # skipping them made this check see 54 files instead of 2,367 under `--root` -- so
        # the mutation that proves it would have been proving a vacuous version of it.
        if not path.is_file():
            continue
        rel_path = path.relative_to(REPO)
        if any(part in COVERAGE_SKIP_DIRS for part in rel_path.parts):
            continue
        if path.suffix.lower() in COVERAGE_BINARY or path.name == ".DS_Store":
            continue
        rel = str(rel_path)
        if rel in watched:
            continue
        for pattern, why in UNWATCHED:
            if _matches(rel, pattern):
                exempt.append((rel, why))
                break
        else:
            unclassified.append(rel)
    return unclassified, exempt


def restricted_for(rel: str) -> frozenset[str] | None:
    """The key set bound on this surface, or None to bind every key.

    Exact path first, then the glob entries, so a specific file can narrow a family.
    """
    if rel in RESTRICTED:
        return RESTRICTED[rel]
    for pattern, keys in RESTRICTED.items():
        if "*" in pattern and fnmatch.fnmatch(rel, pattern):
            return keys
    return None
