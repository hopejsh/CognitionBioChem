def _read(text: str) -> list[tuple[str, int]]:
    return [(k, _n(m.group(1))) for k, pat, _ in RULES for m in pat.finditer(text)]


def _read_worded(text: str) -> list[tuple[str, int]]:
    return [(k, implied) for k, implied, pat, _ in WORDED if pat.search(text)]


def self_test() -> int:
    """Assert the patterns fire where they must and stay silent where they must."""
    failures = 0
    for text, key, value in SELF_TEST:
        got = _read(text)
        if (key, value) not in got:
            print(f"  MISS  {text!r}\n        expected {key}={value}, read {got}")
            failures += 1
    for text, key, value in SELF_TEST_WORDED:
        got = _read_worded(text)
        if (key, value) not in got:
            print(f"  MISS (worded)  {text!r}\n        expected {key}={value}, read {got}")
            failures += 1
    for text in SELF_TEST_SILENT:
        # The worded patterns are read here too. They were not, and that is half the reason
        # the confirmatory denial was never shown to have a false-positive boundary: the
        # silent cases exercised the numeric rules only, so a worded pattern could be
        # widened without anything checking what it started matching.
        got = _read(text) + _read_worded(text)
        # The last case legitimately reports the retained-version count; only a *slate* claim
        # is a false positive there.
        got = [g for g in got if g != ("retained_versions", 11)]
        if got:
            print(f"  FALSE POSITIVE  {text!r}\n        read {got}")
            failures += 1
    for text, forbidden in SELF_TEST_NOT:
        got = [g for g in _read(text) if g[0] == forbidden]
        if got:
            print(f"  FALSE POSITIVE  {text!r}\n        read {got}, and {forbidden} must "
                  "stay silent here")
            failures += 1
    for rel, text, forbidden in SELF_TEST_RESTRICTED:
        allowed = restricted_for(rel)
        fires = [g for g in _read(text) if g[0] == forbidden]
        if allowed is None or (forbidden in allowed and fires):
            print(f"  RESTRICTION LOST  {rel}: {text!r}\n        {forbidden} is bound here "
                  f"and reads {fires}")
            failures += 1
    total = (len(SELF_TEST) + len(SELF_TEST_WORDED) + len(SELF_TEST_SILENT)
             + len(SELF_TEST_NOT) + len(SELF_TEST_RESTRICTED))
    print(f"self-test: {total - failures} passed, {failures} failed")
    return failures


def coverage_report() -> int:
    """`--coverage`: the exemption table, and how many count claims it is standing over.

    An exemption is a promise that a file states no slate count worth binding. That promise
    is checkable, and this is where it gets checked: every exempt file is scanned with the
    full rule table and the disagreements are counted PER PATTERN. A pattern standing over a
    large number is not necessarily wrong -- `reviews/*` stands over the audit transcripts
    that quote every stale sentence they report, and that is the reason it is exempt -- but
    the number is the thing that lets a reader argue with the entry instead of trusting it.

    This is advisory and exits 0 on its own. Turning it into a failure would mean triaging
    133 correct sentences, and a guard that demands that is a guard that gets deleted.
    """
    want = expected()
    watched = {str(p.relative_to(REPO)) for p in surfaces()}
    unclassified, exempt = coverage(watched)
    per_pattern: dict[str, list[tuple[str, str, int, int]]] = {}
    for rel, _why in exempt:
        path = REPO / rel
        try:
            text = path.read_text(errors="replace")
        except OSError:
            continue
        pattern = next(pat for pat, _w in UNWATCHED if _matches(rel, pat))
        for key, pat, claim in RULES:
            for m in pat.finditer(text):
                got = _n(m.group(1))
                if got != want[key]:
                    per_pattern.setdefault(pattern, []).append((rel, key, got, want[key]))

    print("=" * 78)
    print("coverage: every text file is a decision somebody made")
    print("=" * 78)
    print(f"\n{len(watched)} watched · {len(exempt)} exempt · {len(unclassified)} undecided\n")
    for pattern, why in UNWATCHED:
        n_files = sum(1 for rel, _w in exempt if _matches(rel, pattern)
                      and next(p for p, _ in UNWATCHED if _matches(rel, p)) == pattern)
        stale = per_pattern.get(pattern, [])
        flag = f"{len(stale):>4} claim(s) a scan would call stale" if stale else ""
        print(f"  {pattern:<32} {n_files:>5} file(s)  {flag}")
        print(f"      {why[:100]}")
    if unclassified:
        print("\nUNDECIDED:")
        for rel in unclassified:
            print(f"  {rel}")
        return 1
    print("\nAdvisory. The numbers above are the price of each exemption, stated so it can be")
    print("argued with. Nothing here fails a build.\n")
    return 0


def main() -> int:
    """`--root DIR` points every read at another tree.

    Not a convenience. `platform/tools/mutation_suite.py` plants a stale count in a scratch
    copy and requires this guard to fail on it; without a root it can be pointed at, the
    only way to prove that is to damage the repository and undo it afterwards, which is a
    proof nobody runs twice. Every path in this file goes through the module-level `REPO`,
    so rebinding it here rebinds all of them -- including `verify_all.SUITES`, which is read
    from the tree under test rather than from this one, so a mutation that adds a suite
    without correcting the surfaces that count them is caught too.
    """
    global REPO
    if "--root" in sys.argv:
        REPO = Path(sys.argv[sys.argv.index("--root") + 1]).resolve()
    if "--self-test" in sys.argv:
        return 1 if self_test() else 0
    if "--coverage" in sys.argv:
        return coverage_report()
    want = expected()
    hits, checked = scan(want)
    watched_paths = surfaces()
    files = len(watched_paths)
    watched = {str(p.relative_to(REPO)) for p in watched_paths}
    unclassified, exempt = coverage(watched)
    print("=" * 78)
    print("metadata count guard: hand-typed slate counts must equal the artefacts")
    print("=" * 78)
    print("\ncurrent values, read from data/slate.json, prespec/ and verify_all.SUITES:")
    for k in sorted(want):
        print(f"    {k:<22} {want[k]}")
    print(f"\n{checked} count claim(s) bound across {files} surface(s)")
    # The derived half. Printed on every run, because a coverage number that only appears
    # when it is bad is a number nobody has a baseline for.
    print(f"{len(watched) + len(exempt)} text file(s) classified: {len(watched)} watched, "
          f"{len(exempt)} exempted by name in UNWATCHED, {len(unclassified)} undecided")
    if unclassified:
        print("\nFAIL — text file(s) that are neither watched nor exempted:\n")
        for rel in unclassified:
            print(f"  {rel}")
        print("\nEvery text file in this tree must be a decision somebody made. Either add it")
        print("to SURFACES/SURFACE_GLOBS (with a RESTRICTED entry if only some keys apply),")
        print("or add it to UNWATCHED with the reason it states no slate count. This check is")
        print("here because app.js, index.html and verify_all.py each went stale on a surface")
        print("nobody had decided about.\n")
        return 1
    if not hits:
        print("\nPASS — every hand-typed slate count matches the artefact it summarises,")
        print("and every text file in the tree is either watched or exempted by name.\n")
        return 0
    print(f"\nFAIL — {len(hits)} stale count(s):\n")
    for rel, line, claim, got, exp, src in hits:
        print(f"  {rel}:{line}")
        print(f"    {claim}: states {got}, artefacts say {exp}")
        print(f"    | {src}")
    print("\nFix the surface, never the artefact. If the sentence is deliberately quoting a")
    print(f"superseded count, mark that line {EXEMPT_TOKEN} and say why in the text.\n")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
