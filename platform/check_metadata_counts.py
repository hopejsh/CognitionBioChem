#: Surfaces where only SOME count keys are bound, and the reason each exclusion exists.
#:
#: `README.md` is the most-read surface in the repository and it states the slate size, the
#: plan count and the suite count -- including in two badges, which is where a reader looks
#: first and where no scan had ever looked at all. It also, legitimately, counts things that
#: wear the same nouns as the slate totals, and binding those would make the guard cry wolf
#: on correct prose. Every one of these is a real sentence in the file today:
#:
#:   "round-2 re-classified all three hypotheses as threshold criteria"   one STUDY's hypotheses
#:   "All three hypotheses confirmed."                                     one study's, again
#:   "Slate #12 falsified it and that clause is retracted."                a study number
#:   "across the screen's six retained versions"                           one study's versions
#:   "that run reported nine distinct designs, and the current v8 ..."     a superseded version
#:
#: So README is bound to the three keys that have no per-study meaning: a study is either in
#: the slate or not, a plan is either registered or not, and a suite either runs or does not.
#: Narrowing the surface is the honest move; the alternative is a guard nobody believes.
#: A fourth key was added after a cold reader took "including the eleven falsifications" out
#: of the How-to-cite block as this project's headline: `falsifications`, the noun. It is
#: bound here and `falsified`, the adjective, still is not -- which is exactly why they are
#: separate keys. The adjective collides with a study number in this file; the noun collides
#: with nothing, and the sentence it guards is the one a citer reads.
#:
#: IS THE RESTRICTION STILL RIGHT? In kind, yes; in reach, it was not, and the same reader
#: who found `falsifications` would have found this. README's summary table -- line 90, the
#: first quantitative statement a visitor reads -- says "9 pre-registered studies, 28
#: hypotheses of which 27 are decided". `studies` was bound there. `hypotheses` was not, and
#: neither was the decided total, because `hypotheses` legitimately counts one study's three
#: on three other lines of the same file. So the most-read count in the repository was
#: unbound on a technicality about a different sentence.
#:
#: A whole-key exclusion is too blunt an instrument: it excludes the phrasings that CANNOT
#: collide along with the one that can. The fix is the one already proven on
#: `falsified`/`falsifications` -- split the key, so the collision-free phrasing gets bound
#: where the colliding one cannot be. `hypotheses_in_roster` binds only the form that names
#: the hypothesis count in the same breath as the study count, which no per-study sentence
#: can wear; `decided` binds "of which N are decided", which is a slate-wide split by
#: construction. Both are added to README here. `confirmations` is the same move for
#: `confirmed`, whose adjective collides with "All three hypotheses confirmed."
#:
#: What stays excluded splits in two, and the split is worth stating because only half of it
#: is evidence:
#:
#:   demonstrated. `hypotheses` reads 3 on three lines, `falsified` reads 12 off "Slate #12
#:   falsified it", `retained_versions` reads 6, `distinct_peptides` reads 9. Those four
#:   sentences are in SELF_TEST_RESTRICTED below, so the exclusion cannot quietly widen back
#:   and a rewrite of the prose that removes the collision will show up as a stale test.
#:
#:   by principle, with no collision in the file today. `confirmed`, `not_tested`, the two
#:   decision kinds, `deviations`: each counts a quantity that EXISTS per study, so README
#:   is one per-study table away from a false positive. They stay out because the shape of
#:   the file invites the sentence, not because the sentence is already there.
#:
#: And the honest caveat on the noun forms: `falsifications` is bound on README and NOT on
#: app.js, because app.js line 1153 really does say "only two falsifications in the slate"
#: while quoting a misreading it corrects. Nominalisation does not make a count immune to a
#: per-study reading -- it only happens to have no per-study reading on the surfaces where it
#: is bound. That is a per-file judgement, checked against the file, not a principle. Anyone
#: widening this table should run the probe the way it was run here: scan the surface with
#: every key enabled and read what the excluded keys actually report.
#: `app.js` and `index.html` are bound to the same three keys as README, plus the two
#: confirmatory ones and the peptide counts -- the claims that have no per-study meaning and
#: that these two files actually make. They are excluded from the rest for a reason a scan of
#: them makes obvious: `app.js` carries JS comments that quote superseded sentences in order
#: to explain why the code no longer contains them, and it refers to studies by number.
#: "Study #12 falsified that clause" reads to the `falsified` rule as a slate total of 12.
